using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace DictionaryManipulate.TextPocess
{
    //-------------------------------------------------------------------------------------------------------------------
    // class Letter
    //-------------------------------------------------------------------------------------------------------------------
    public class Letter
    {
        private Letter chield;
        private Letter next;
        private char data;
        private int count;
        private object tag;
        //-------------------------------------------------------------------------------------------------------------------
        public Letter(char pData)
        {
            data = pData;
        }
        //-------------------------------------------------------------------------------------------------------------------
        public Letter Chield
        {
            get
            {
                return chield;
            }
            set
            {
                chield = value;
            }
        }
        //-------------------------------------------------------------------------------------------------------------------
        public Letter Next
        {
            get
            {
                return next;
            }
            set
            {
                next = value;
            }
        }
        //-------------------------------------------------------------------------------------------------------------------
        public char Data
        {
            get
            {
                return data;
            }
        }
        //-------------------------------------------------------------------------------------------------------------------
        public object Tag
        {
            get
            {
                return tag;
            }
            set
            {
                tag = value;
            }
        }
        //-------------------------------------------------------------------------------------------------------------------
        public int Count
        {
            get
            {
                return count;
            }
        }
        //-------------------------------------------------------------------------------------------------------------------
        public void Increment()
        {
            count++;
        }
        //-------------------------------------------------------------------------------------------------------------------
        public override string ToString()
        {
            return Data.ToString();
        }
        //-------------------------------------------------------------------------------------------------------------------
    }
    //-------------------------------------------------------------------------------------------------------------------
}
